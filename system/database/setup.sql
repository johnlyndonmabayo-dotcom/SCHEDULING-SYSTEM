-- ShiftFlow Supabase setup (review before running on an existing production database).
-- Back up existing data first. This script does not delete existing rows.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'employee' check (role in ('admin', 'employee')),
  created_at timestamptz not null default now()
);

create table if not exists public.employees (
  employee_id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  full_name text not null,
  position text not null,
  department text not null,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  created_at timestamptz not null default now()
);

create table if not exists public.schedules (
  schedule_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(employee_id) on delete restrict,
  work_date date not null,
  start_time time not null,
  end_time time not null,
  shift text not null,
  status text not null default 'Pending' check (status in ('Pending', 'Approved', 'Cancelled', 'Rejected')),
  created_at timestamptz not null default now(),
  constraint schedule_valid_time check (start_time <> end_time)
);

-- Add fields required by the app when tables already exist.
alter table public.profiles add column if not exists full_name text not null default '';
alter table public.profiles add column if not exists role text not null default 'employee';
alter table public.employees add column if not exists full_name text not null default '';
alter table public.employees add column if not exists position text not null default '';
alter table public.employees add column if not exists department text not null default '';
alter table public.employees add column if not exists user_id uuid references auth.users(id) on delete set null;
alter table public.employees add column if not exists status text not null default 'Active';
alter table public.employees add column if not exists created_at timestamptz not null default now();
alter table public.schedules add column if not exists employee_id bigint references public.employees(employee_id) on delete restrict;
alter table public.schedules add column if not exists work_date date not null default current_date;
alter table public.schedules add column if not exists start_time time not null default time '09:00';
alter table public.schedules add column if not exists end_time time not null default time '17:00';
alter table public.schedules add column if not exists shift text not null default 'Morning';
alter table public.schedules add column if not exists status text not null default 'Pending';
alter table public.schedules add column if not exists created_at timestamptz not null default now();

create index if not exists employees_user_id_idx on public.employees(user_id);
create index if not exists schedules_employee_date_idx on public.schedules(employee_id, work_date);
create index if not exists schedules_work_date_idx on public.schedules(work_date);

-- Helper functions avoid recursive profile-table RLS checks.
create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid() limit 1;
$$;

create or replace function public.current_employee_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select employee_id from public.employees where user_id = auth.uid() limit 1;
$$;

-- Automatically create a basic employee profile after a Supabase Auth signup.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    'employee'
  )
  on conflict (id) do nothing;

  -- Employee self-registration: create an inactive employee record.
  -- An administrator must activate it before it can be scheduled.
  if nullif(trim(coalesce(new.raw_user_meta_data ->> 'position', '')), '') is not null
     and nullif(trim(coalesce(new.raw_user_meta_data ->> 'department', '')), '') is not null then
    insert into public.employees (user_id, full_name, position, department, status)
    values (
      new.id,
      coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), ''),
      trim(new.raw_user_meta_data ->> 'position'),
      trim(new.raw_user_meta_data ->> 'department'),
      'Inactive'
    )
    on conflict (user_id) do nothing;
  end if;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_shiftflow on auth.users;
create trigger on_auth_user_created_shiftflow
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

alter table public.profiles enable row level security;
alter table public.employees enable row level security;
alter table public.schedules enable row level security;

drop policy if exists "profiles read self or admin" on public.profiles;
create policy "profiles read self or admin" on public.profiles
for select to authenticated
using (id = auth.uid() or public.current_user_role() = 'admin');

drop policy if exists "profiles update self or admin" on public.profiles;
drop policy if exists "profiles update admin only" on public.profiles;
create policy "profiles update admin only" on public.profiles
for update to authenticated
using (public.current_user_role() = 'admin')
with check (public.current_user_role() = 'admin');

drop policy if exists "employees admin all and employee self read" on public.employees;
create policy "employees admin all and employee self read" on public.employees
for select to authenticated
using (public.current_user_role() = 'admin' or user_id = auth.uid());

drop policy if exists "employees admin insert" on public.employees;
create policy "employees admin insert" on public.employees
for insert to authenticated
with check (public.current_user_role() = 'admin');

drop policy if exists "employees admin update" on public.employees;
create policy "employees admin update" on public.employees
for update to authenticated
using (public.current_user_role() = 'admin')
with check (public.current_user_role() = 'admin');

drop policy if exists "employees admin delete" on public.employees;
create policy "employees admin delete" on public.employees
for delete to authenticated
using (public.current_user_role() = 'admin');

drop policy if exists "schedules admin all and employee self read" on public.schedules;
create policy "schedules admin all and employee self read" on public.schedules
for select to authenticated
using (
  public.current_user_role() = 'admin'
  or employee_id = public.current_employee_id()
);

drop policy if exists "schedules admin insert" on public.schedules;
drop policy if exists "schedules admin or employee own insert" on public.schedules;
create policy "schedules admin or employee own insert" on public.schedules
for insert to authenticated
with check (
  public.current_user_role() = 'admin'
  or (
    employee_id = public.current_employee_id()
    and exists (
      select 1
      from public.employees e
      where e.employee_id = public.schedules.employee_id
        and e.user_id = auth.uid()
        and e.status = 'Active'
    )
  )
);

drop policy if exists "schedules admin update" on public.schedules;
create policy "schedules admin update" on public.schedules
for update to authenticated
using (public.current_user_role() = 'admin')
with check (public.current_user_role() = 'admin');

drop policy if exists "schedules admin delete" on public.schedules;
create policy "schedules admin delete" on public.schedules
for delete to authenticated
using (public.current_user_role() = 'admin');

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.profiles to authenticated;
grant select, insert, update, delete on public.employees to authenticated;
grant select, insert, update, delete on public.schedules to authenticated;
grant execute on function public.current_user_role() to authenticated;
grant execute on function public.current_employee_id() to authenticated;
